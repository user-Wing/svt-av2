/*
 * Inverse 1-D, AVM reading order. idct.c:42-45 sums the matrix COLUMN indexed by
 * the output sample:
 *   dst[o] = sum_k tx_mat[k * size + o] * src[k]
 * then `(t + add) >> shift` with `add = 1 << (shift - 1)`, clipped. Arithmetic
 * (floor) shift on the signed value.
 */
static void ref_inv_1d(const int* src, int* dst, int shift, int size, int lo, int hi) {
    const int* m = ref_matrix((uint32_t)size);
    const int add = 1 << (shift - 1);
    for (int o = 0; o < size; ++o) {
        long long t = 0;
        for (int k = 0; k < size; ++k) {
            t += (long long)m[k * size + o] * src[k];
        }
        dst[o] = clampv((int)((t + add) >> shift), lo, hi);
    }
}

/* Forward 1-D, hybrid_fwd_txfm.c reading order: the matrix ROW indexed by the
 * output frequency.
 *   dst[f] = sum_k tx_mat[f * size + k] * src[k]
 * The forward path has no clamp. */
static void ref_fwd_1d(const int* src, int* dst, int shift, int size) {
    const int* m = ref_matrix((uint32_t)size);
    const int add = (shift > 0) ? (1 << (shift - 1)) : 0;
    for (int f = 0; f < size; ++f) {
        long long t = 0;
        for (int k = 0; k < size; ++k) {
            t += (long long)m[f * size + k] * src[k];
        }
        dst[f] = (int)((t + add) >> shift);
    }
}

static int log2u(uint32_t v) {
    int l = 0;
    while ((1u << l) < v) ++l;
    return l;
}

