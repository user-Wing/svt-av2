static void test_reference_tables(void) {
    const uint32_t sizes[5] = { 4, 8, 16, 32, 64 };
    for (int s = 0; s < 5; ++s) {
        const uint32_t n = sizes[s];
        const int* m = svt_av2_tx_dct2_matrix(n);
        SVT_TEST_CHECK(m != NULL);
        if (m == NULL) continue;
        const int* r = ref_matrix(n);
        for (uint32_t i = 0; i < n * n; ++i) {
            SVT_TEST_CHECK_EQ_INT(m[i], r[i]);
        }
    }
    /* unsupported lengths must return NULL, not a wrong table */
    SVT_TEST_CHECK(svt_av2_tx_dct2_matrix(2) == NULL);
    SVT_TEST_CHECK(svt_av2_tx_dct2_matrix(7) == NULL);

    for (unsigned i = 0; i < sizeof(k_ref_shifts) / sizeof(k_ref_shifts[0]); ++i) {
        int a = -1, b = -1;
        SVT_TEST_CHECK_EQ_INT(svt_av2_tx_inv_shifts(k_ref_shifts[i].w, k_ref_shifts[i].h, &a, &b), 0);
        SVT_TEST_CHECK_EQ_INT(a, k_ref_shifts[i].inv0);
        SVT_TEST_CHECK_EQ_INT(b, k_ref_shifts[i].inv1);
        SVT_TEST_CHECK_EQ_INT(svt_av2_tx_fwd_shifts(k_ref_shifts[i].w, k_ref_shifts[i].h, &a, &b), 0);
        SVT_TEST_CHECK_EQ_INT(a, k_ref_shifts[i].fwd0);
        SVT_TEST_CHECK_EQ_INT(b, k_ref_shifts[i].fwd1);
    }
}

static void test_geometry(void) {
    /* supported geometries and their pels / tx_scale. The (A)-path sizes are
     * TX_32X32 (chroma, tx_scale 1) and TX_64X64 (luma, tx_scale 2). */
    const uint32_t ok[][2] = { { 4, 4 }, { 8, 8 }, { 16, 16 }, { 4, 8 }, { 8, 4 },
                               { 4, 16 }, { 16, 4 }, { 8, 16 }, { 16, 8 },
                               { 32, 32 }, { 64, 64 } };
    for (unsigned i = 0; i < sizeof(ok) / sizeof(ok[0]); ++i) {
        const uint32_t w = ok[i][0], h = ok[i][1];
        SVT_TEST_CHECK(svt_av2_tx_supported(w, h));
        /* 00's ruling (甲): length == av2_get_max_eob() == min(w,32)*min(h,32).
         * Written as the general formula so a wrong 64-special-case is caught. */
        const size_t mw = (w > 32) ? 32u : w;
        const size_t mh = (h > 32) ? 32u : h;
        SVT_TEST_CHECK_EQ_INT((long long)svt_av2_tx_coeff_count(w, h), (long long)(mw * mh));
        SVT_TEST_CHECK_EQ_INT(svt_av2_tx_log_scale(w, h), svt_av2_tx_scale(w, h));
    }
    /* Explicit anchors for the values 00 enumerated, including the TX_64X64
     * grid (1024) and the non-square 32/64 lengths the min() rule produces. */
    SVT_TEST_CHECK_EQ_INT((long long)svt_av2_tx_coeff_count(64, 64), 1024);
    SVT_TEST_CHECK_EQ_INT((long long)svt_av2_tx_coeff_count(32, 32), 1024);
    SVT_TEST_CHECK_EQ_INT((long long)svt_av2_tx_coeff_count(16, 16), 256);
    /* tx_scale boundary cases, pinned so a change cannot silently move the
     * quantizer's shift: 16x16 = 256 pels is NOT > 256, so it is 0. */
    SVT_TEST_CHECK_EQ_INT(svt_av2_tx_scale(4, 4), 0);
    SVT_TEST_CHECK_EQ_INT(svt_av2_tx_scale(16, 16), 0);
    SVT_TEST_CHECK_EQ_INT(svt_av2_tx_scale(16, 32), 1);
    SVT_TEST_CHECK_EQ_INT(svt_av2_tx_scale(32, 32), 1);
    SVT_TEST_CHECK_EQ_INT(svt_av2_tx_scale(32, 64), 2);
    SVT_TEST_CHECK_EQ_INT(svt_av2_tx_scale(64, 64), 2);

    /*
     * Caller-convention anchor (reported by T010): tx_scale is defined on the
     * ORIGINAL geometry, not on the carried coefficient grid. TX_64X64 packs
     * into a 32x32 grid, so coeff_count cannot tell the two apart, but the
     * scale MUST be 2 for (64,64) and 1 for (32,32). If a caller passes the
     * grid size the dequantizer under-shifts by one bit (every dqcoeff 2x)
     * silently. Pin both, and pin that the counts are indeed ambiguous so the
     * reason this anchor exists stays visible.
     */
    SVT_TEST_CHECK_EQ_INT((long long)svt_av2_tx_coeff_count(64, 64),
                          (long long)svt_av2_tx_coeff_count(32, 32));
    SVT_TEST_CHECK(svt_av2_tx_scale(64, 64) != svt_av2_tx_scale(32, 32));

    /* Unsupported: zero, odd, non power-of-two, and rectangles outside
     * the current 8:1 subset. */
    const uint32_t bad[][2] = { { 0, 0 }, { 4, 0 }, { 0, 4 }, { 2, 2 }, { 6, 6 },
                                { 4, 64 }, { 64, 4 }, { 8, 128 }, { 128, 8 },
                                { 4, 128 }, { 1, 1 }, { 3, 4 } };
    for (unsigned i = 0; i < sizeof(bad) / sizeof(bad[0]); ++i) {
        SVT_TEST_CHECK(!svt_av2_tx_supported(bad[i][0], bad[i][1]));
        SVT_TEST_CHECK_EQ_INT((long long)svt_av2_tx_coeff_count(bad[i][0], bad[i][1]), 0);
    }
}

static void test_round_shift(void) {
    /* exactly representable: no rounding */
    SVT_TEST_CHECK_EQ_INT(svt_av2_tx_round_shift(128, 7), 1);
    SVT_TEST_CHECK_EQ_INT(svt_av2_tx_round_shift(-128, 7), -1);
    /* ties go toward +inf because the shift is a floor on (v + half) */
    SVT_TEST_CHECK_EQ_INT(svt_av2_tx_round_shift(64, 7), 1);   /* 0.5 -> 1 */
    SVT_TEST_CHECK_EQ_INT(svt_av2_tx_round_shift(-64, 7), 0);  /* -0.5 -> 0 (not -1) */
    /* the negative side is NOT round-half-away-from-zero */
    SVT_TEST_CHECK_EQ_INT(svt_av2_tx_round_shift(-63, 7), 0);
    SVT_TEST_CHECK_EQ_INT(svt_av2_tx_round_shift(63, 7), 0);
    SVT_TEST_CHECK_EQ_INT(svt_av2_tx_round_shift(-65, 7), -1);
    SVT_TEST_CHECK_EQ_INT(svt_av2_tx_round_shift(65, 7), 1);
    /* large magnitude stays in int32 after the shift */
    SVT_TEST_CHECK_EQ_INT(svt_av2_tx_round_shift((int64_t)1 << 40, 12), (int32_t)((1LL << 40) >> 12));
    SVT_TEST_CHECK_EQ_INT(svt_av2_tx_round_shift(-((int64_t)1 << 40), 12), -((int32_t)((1LL << 40) >> 12)));

    /*
     * Ordering anchor: the module NEVER applies a descaling shift before
     * rounding, and never applies `tx_scale` at all (that is the quantizer's).
     * This pins the distinction that a T010-side bug turned on: a shift that
     * happens before the +half truncates odd intermediate values, and is only
     * observable when the shift count is non-zero (log_scale > 0). Round first,
     * then shift, so a large odd value survives:
     */
    SVT_TEST_CHECK_EQ_INT(svt_av2_tx_round_shift(255, 1), 128);   /* (255+1)>>1 */
    SVT_TEST_CHECK_EQ_INT(svt_av2_tx_round_shift(255, 2), 64);    /* (255+2)>>2 */
    SVT_TEST_CHECK_EQ_INT(svt_av2_tx_round_shift(255, 3), 32);    /* (255+4)>>3 */
    /* shift-first would give 127/63/31 here; the module must not. */
    SVT_TEST_CHECK_EQ_INT(svt_av2_tx_round_shift(511, 1), 256);
    /* a large odd input whose post-round value still fits int32 */
    SVT_TEST_CHECK_EQ_INT(svt_av2_tx_round_shift((int64_t)2000000001, 1), (int32_t)(((int64_t)2000000001 + 1) >> 1));
    SVT_TEST_CHECK_EQ_INT(svt_av2_tx_round_shift(-(int64_t)2000000001, 1), (int32_t)((-(int64_t)2000000001 + 1) >> 1));
}

static void test_inv_1d_identity(void) {
    /* the 1-D inverse equals the independent column-sum model, including clamp */
    int src[SVT_AV2_TX_MAX_DIM], got[SVT_AV2_TX_MAX_DIM], exp[SVT_AV2_TX_MAX_DIM];
    for (int size = 4; size <= 64; size *= 2) {
        const int shift = (size == 4) ? 7 : (size == 8) ? 7 : (size == 16) ? 6 : 6;
        for (int t = 0; t < 50; ++t) {
            for (int k = 0; k < size; ++k) src[k] = (k * 271 + t * 9767) % 65537 - 32768;
            svt_av2_tx_inv_1d(src, got, shift, (uint32_t)size, 1, -1024, 1023);
            ref_inv_1d(src, exp, shift, size, -1024, 1023);
            for (int k = 0; k < size; ++k) SVT_TEST_CHECK_EQ_INT(got[k], exp[k]);
        }
    }
    /* clamp bounds are respected exactly. Build a source that provably drives
     * one output past the high bound: dst[o] = sum_k M[k][o] * src[k], so with
     * src[k] = M[k][o0] the output o0 is sum_k M[k][o0]^2, whose magnitude is
     * huge for the +-64..90 matrix entries. */
    {
        const int* m = svt_av2_tx_dct2_matrix(4);
        for (int o = 0; o < 4; ++o) {
            for (int k = 0; k < 4; ++k) src[k] = 1000 * m[k * 4 + o];
            svt_av2_tx_inv_1d(src, got, 7, 4, 1, -256, 255);
            for (int k = 0; k < 4; ++k) {
                SVT_TEST_CHECK(got[k] >= -256 && got[k] <= 255);
            }
            /* the driven output saturates at the matching extreme */
            long long dc = 0;
            for (int k = 0; k < 4; ++k) dc += (long long)m[k * 4 + o] * (1000 * m[k * 4 + o]);
            SVT_TEST_CHECK_EQ_INT(got[o], dc > 0 ? 255 : -256);
        }
        /* an all-+32767 source must stay inside the clamp everywhere, and must
         * saturate at least one output (the matrix is signed, so at least one
         * column sum is large in magnitude) */
        for (int k = 0; k < 4; ++k) src[k] = 32767;
        svt_av2_tx_inv_1d(src, got, 7, 4, 1, -256, 255);
        int saturated = 0;
        for (int k = 0; k < 4; ++k) {
            SVT_TEST_CHECK(got[k] >= -256 && got[k] <= 255);
            if (got[k] == 255 || got[k] == -256) saturated = 1;
        }
        SVT_TEST_CHECK(saturated);
    }
}

static void test_fwd_1d_identity(void) {
    /* the 1-D forward equals the independent row-sum model */
    int src[SVT_AV2_TX_MAX_DIM], got[SVT_AV2_TX_MAX_DIM], exp[SVT_AV2_TX_MAX_DIM];
    for (int size = 4; size <= 64; size *= 2) {
        /* use the real AVM first-pass shift for each length, not a fixed 9, so
         * the 32/64 round-then-shift path is exercised at its true shift count. */
        const int shift = (size == 4) ? 1 : (size == 8) ? 2 : (size == 16) ? 2 : (size == 32) ? 3 : 3;
        for (int t = 0; t < 50; ++t) {
            for (int k = 0; k < size; ++k) src[k] = ((k * 137 + t * 4051) % 511) - 255;
            svt_av2_tx_fwd_1d(src, got, shift, (uint32_t)size, 1);
            ref_fwd_1d(src, exp, shift, size);
            for (int k = 0; k < size; ++k) SVT_TEST_CHECK_EQ_INT(got[k], exp[k]);
        }
        /* extreme positive/negative to catch a shift-before-round slip */
        for (int k = 0; k < size; ++k) src[k] = (k & 1) ? 32767 : -32768;
        svt_av2_tx_fwd_1d(src, got, shift, (uint32_t)size, 1);
        ref_fwd_1d(src, exp, shift, size);
        for (int k = 0; k < size; ++k) SVT_TEST_CHECK_EQ_INT(got[k], exp[k]);
    }
}

/* helper: compare a full block against the inverse model */
static void check_inv_block(const int32_t* dq, uint32_t w, uint32_t h, const char* tag) {
    int16_t got[SVT_AV2_TX_MAX_PELS];
    int16_t exp[SVT_AV2_TX_MAX_PELS];
    (void)tag;
    SVT_TEST_CHECK_EQ_INT(svt_av2_inv_transform(dq, got, w, h), SVT_AV2_TX_OK);
    ref_inv_2d(dq, exp, w, h, 8);
    for (uint32_t i = 0; i < w * h; ++i) SVT_TEST_CHECK_EQ_INT(got[i], exp[i]);
}

static void check_fwd_block(const int16_t* res, uint32_t w, uint32_t h) {
    int32_t got[SVT_AV2_TX_MAX_PELS];
    int32_t exp[SVT_AV2_TX_MAX_PELS];
    SVT_TEST_CHECK_EQ_INT(svt_av2_fwd_transform(res, got, w, h), SVT_AV2_TX_OK);
    ref_fwd_2d(res, exp, w, h);
    const size_t n = svt_av2_tx_coeff_count(w, h);
    for (size_t i = 0; i < n; ++i) SVT_TEST_CHECK_EQ_INT(got[i], exp[i]);
}

static void test_inverse_blocks_all_sizes(void) {
    static const uint32_t geo[][2] = { { 4, 4 }, { 8, 8 }, { 16, 16 }, { 32, 32 }, { 64, 64 },
                                       { 4, 8 }, { 8, 4 },
                                       { 4, 16 }, { 16, 4 }, { 8, 16 }, { 16, 8 } };
    for (unsigned g = 0; g < sizeof(geo) / sizeof(geo[0]); ++g) {
        const uint32_t w = geo[g][0], h = geo[g][1];
        const uint32_t n = w * h;
        int32_t dq[SVT_AV2_TX_MAX_PELS];

        /* all zero */
        memset(dq, 0, sizeof(dq));
        check_inv_block(dq, w, h, "zero");

        /* constant (DC only): nonzero DC, zero AC */
        memset(dq, 0, sizeof(dq));
        dq[0] = 640;
        check_inv_block(dq, w, h, "dc");

        /* single AC coefficient, three different positions */
        for (uint32_t pos = 1; pos < n; pos += (n > 4 ? n / 3 : 1)) {
            memset(dq, 0, sizeof(dq));
            dq[pos] = 300;
            check_inv_block(dq, w, h, "ac");
            dq[pos] = -300;
            check_inv_block(dq, w, h, "ac-neg");
        }

        /* negative DC */
        memset(dq, 0, sizeof(dq));
        dq[0] = -640;
        check_inv_block(dq, w, h, "dc-neg");

        /* largest / most negative coefficient magnitudes (clamp exercised) */
        for (uint32_t i = 0; i < n; ++i) dq[i] = 32767;
        check_inv_block(dq, w, h, "max");
        for (uint32_t i = 0; i < n; ++i) dq[i] = -32768;
        check_inv_block(dq, w, h, "min");

        /* alternating extremes (highest frequency energy) */
        for (uint32_t y = 0; y < h; ++y) {
            for (uint32_t x = 0; x < w; ++x) {
                dq[y * w + x] = ((x + y) & 1) ? 32767 : -32768;
            }
        }
        check_inv_block(dq, w, h, "alt");

        /* fixed-seed random blocks, >= 100 per size */
        for (int t = 0; t < 120; ++t) {
            for (uint32_t i = 0; i < n; ++i) {
                dq[i] = ((int)(i * 131u + (unsigned)t * 7919u) % 65536) - 32768;
            }
            check_inv_block(dq, w, h, "rand");
        }
    }
}

static void test_forward_blocks_all_sizes(void) {
    static const uint32_t geo[][2] = { { 4, 4 }, { 8, 8 }, { 16, 16 }, { 32, 32 }, { 64, 64 },
                                       { 4, 8 }, { 8, 4 },
                                       { 4, 16 }, { 16, 4 }, { 8, 16 }, { 16, 8 } };
    for (unsigned g = 0; g < sizeof(geo) / sizeof(geo[0]); ++g) {
        const uint32_t w = geo[g][0], h = geo[g][1];
        const uint32_t n = w * h;
        int16_t res[SVT_AV2_TX_MAX_PELS];

        /* all zero -> all zero */
        memset(res, 0, sizeof(res));
        check_fwd_block(res, w, h);

        /* constant block -> pure DC, all AC exactly zero (the documented
         * degenerate case; this is a strong, reference-independent property) */
        for (uint32_t i = 0; i < n; ++i) res[i] = 10;
        {
            int32_t coeff[SVT_AV2_TX_MAX_PELS];
            SVT_TEST_CHECK_EQ_INT(svt_av2_fwd_transform(res, coeff, w, h), SVT_AV2_TX_OK);
            const size_t cn = svt_av2_tx_coeff_count(w, h);
            for (size_t i = 1; i < cn; ++i) SVT_TEST_CHECK_EQ_INT(coeff[i], 0);
            check_fwd_block(res, w, h);
        }

        /* single impulse */
        for (uint32_t pos = 0; pos < n; pos += (n > 4 ? n / 3 : 1)) {
            memset(res, 0, sizeof(res));
            res[pos] = 100;
            check_fwd_block(res, w, h);
            res[pos] = -100;
            check_fwd_block(res, w, h);
        }

        /* horizontal and vertical stripes */
        for (uint32_t y = 0; y < h; ++y) {
            for (uint32_t x = 0; x < w; ++x) res[y * w + x] = (int16_t)((x & 1) ? 200 : -200);
        }
        check_fwd_block(res, w, h);
        for (uint32_t y = 0; y < h; ++y) {
            for (uint32_t x = 0; x < w; ++x) res[y * w + x] = (int16_t)((y & 1) ? 200 : -200);
        }
        check_fwd_block(res, w, h);

        /* largest positive / negative residual */
        for (uint32_t i = 0; i < n; ++i) res[i] = 255;
        check_fwd_block(res, w, h);
        for (uint32_t i = 0; i < n; ++i) res[i] = -255;
        check_fwd_block(res, w, h);

        /* fixed-seed random residuals, >= 100 per size */
        for (int t = 0; t < 120; ++t) {
            for (uint32_t i = 0; i < n; ++i) {
                res[i] = (int16_t)(((int)(i * 57u + (unsigned)t * 1013u) % 511) - 255);
            }
            check_fwd_block(res, w, h);
        }
    }
}

static void test_error_paths(void) {
    int32_t dq[SVT_AV2_TX_MAX_PELS];
    int16_t res[SVT_AV2_TX_MAX_PELS];
    int32_t coeff[SVT_AV2_TX_MAX_PELS];
    memset(dq, 0, sizeof(dq));
    memset(res, 0, sizeof(res));

    SVT_TEST_CHECK_EQ_INT(svt_av2_inv_transform(NULL, res, 4, 4), SVT_AV2_TX_ERR_NULL);
    SVT_TEST_CHECK_EQ_INT(svt_av2_inv_transform(dq, NULL, 4, 4), SVT_AV2_TX_ERR_NULL);
    SVT_TEST_CHECK_EQ_INT(svt_av2_inv_transform(dq, res, 8, 128), SVT_AV2_TX_ERR_UNSUPPORTED);
    SVT_TEST_CHECK_EQ_INT(svt_av2_inv_transform(dq, res, 6, 6), SVT_AV2_TX_ERR_UNSUPPORTED);

    SVT_TEST_CHECK_EQ_INT(svt_av2_fwd_transform(NULL, coeff, 4, 4), SVT_AV2_TX_ERR_NULL);
    SVT_TEST_CHECK_EQ_INT(svt_av2_fwd_transform(res, NULL, 4, 4), SVT_AV2_TX_ERR_NULL);
    SVT_TEST_CHECK_EQ_INT(svt_av2_fwd_transform(res, coeff, 128, 8), SVT_AV2_TX_ERR_UNSUPPORTED);

    /* out-of-range residual is refused, not silently clamped */
    memset(res, 0, sizeof(res));
    res[0] = 256;
    SVT_TEST_CHECK_EQ_INT(svt_av2_fwd_transform(res, coeff, 4, 4), SVT_AV2_TX_ERR_RANGE);
    res[0] = -256;
    SVT_TEST_CHECK_EQ_INT(svt_av2_fwd_transform(res, coeff, 4, 4), SVT_AV2_TX_ERR_RANGE);
    res[0] = 255;
    SVT_TEST_CHECK_EQ_INT(svt_av2_fwd_transform(res, coeff, 4, 4), SVT_AV2_TX_OK);
    res[0] = -255;
    SVT_TEST_CHECK_EQ_INT(svt_av2_fwd_transform(res, coeff, 4, 4), SVT_AV2_TX_OK);
}

static void test_inv_output_is_residual_range(void) {
    /* The inverse output is a residual clamped to [-256, 255], NOT [0, 255].
     * Feed a DC that drives a sample strongly negative and confirm the negative
     * residual survives instead of being clipped to 0. */
    int32_t dq[SVT_AV2_TX_MAX_PELS];
    int16_t res[SVT_AV2_TX_MAX_PELS];
    memset(dq, 0, sizeof(dq));
    dq[0] = -32768; /* strongly negative DC */
    SVT_TEST_CHECK_EQ_INT(svt_av2_inv_transform(dq, res, 8, 8), SVT_AV2_TX_OK);
    int saw_negative = 0;
    for (int i = 0; i < 64; ++i) {
        if (res[i] < 0) saw_negative = 1;
        SVT_TEST_CHECK(res[i] >= -256 && res[i] <= 255);
    }
    SVT_TEST_CHECK(saw_negative);

    memset(dq, 0, sizeof(dq));
    dq[0] = 32767; /* strongly positive DC */
    SVT_TEST_CHECK_EQ_INT(svt_av2_inv_transform(dq, res, 8, 8), SVT_AV2_TX_OK);
    int saw_positive = 0;
    for (int i = 0; i < 64; ++i) {
        if (res[i] > 0) saw_positive = 1;
        SVT_TEST_CHECK(res[i] >= -256 && res[i] <= 255);
    }
    SVT_TEST_CHECK(saw_positive);
}

static void test_unsupported_no_write(void) {
    /* an unsupported geometry must not touch the output buffer */
    int32_t dq[SVT_AV2_TX_MAX_PELS];
    int16_t res[SVT_AV2_TX_MAX_PELS];
    for (int i = 0; i < SVT_AV2_TX_MAX_PELS; ++i) { dq[i] = 7; res[i] = 1234; }
    SVT_TEST_CHECK_EQ_INT(svt_av2_inv_transform(dq, res, 4, 64), SVT_AV2_TX_ERR_UNSUPPORTED);
    for (int i = 0; i < SVT_AV2_TX_MAX_PELS; ++i) SVT_TEST_CHECK_EQ_INT(res[i], 1234);
}

static void test_bd_random_independent_models(void) {
    uint32_t seed = 0x31415926u;
    int16_t input[SVT_AV2_TX_MAX_PELS], inverse[SVT_AV2_TX_MAX_PELS], expected_inverse[SVT_AV2_TX_MAX_PELS];
    int32_t coeff[SVT_AV2_TX_MAX_PELS], expected[SVT_AV2_TX_MAX_PELS], dq[SVT_AV2_TX_MAX_PELS];
    for (uint32_t bd = 8; bd <= 10; bd += 2) {
        const int maximum = (1 << bd) - 1;
        for (size_t g = 0; g < sizeof(k_ref_shifts) / sizeof(k_ref_shifts[0]); ++g) {
            const uint32_t w = k_ref_shifts[g].w, h = k_ref_shifts[g].h;
            const uint32_t count = w * h, carried = (w > 32 ? 32 : w) * (h > 32 ? 32 : h);
            for (uint32_t trial = 0; trial < 100; ++trial) {
                for (uint32_t i = 0; i < count; ++i) {
                    seed = seed * 1664525u + 1013904223u;
                    input[i] = (int16_t)((int)(seed % (uint32_t)(2 * maximum + 1)) - maximum);
                }
                ref_fwd_2d(input, expected, w, h);
                SVT_TEST_CHECK_EQ_INT(svt_av2_fwd_transform_bd(input, coeff, w, h, bd), SVT_AV2_TX_OK);
                SVT_TEST_CHECK(memcmp(coeff, expected, carried * sizeof(*coeff)) == 0);
                /* Independent inverse inputs exercise both intermediate and final clamps. */
                for (uint32_t i = 0; i < carried; ++i) {
                    seed = seed * 1664525u + 1013904223u;
                    dq[i] = (int32_t)(seed % (1u << (bd + 10))) - (1 << (bd + 9));
                }
                ref_inv_2d(dq, expected_inverse, w, h, bd);
                SVT_TEST_CHECK_EQ_INT(svt_av2_inv_transform_bd(dq, inverse, w, h, bd), SVT_AV2_TX_OK);
                SVT_TEST_CHECK(memcmp(inverse, expected_inverse, count * sizeof(*inverse)) == 0);
            }
        }
    }
}

