/*
 * T009 unit tests: scalar forward / inverse integer transforms (DCT_DCT).
 *
 * Layering, kept separate so a failure localises itself:
 *
 *   1. Reference-table tests. The kernel matrices and the shift tables are
 *      compared against values transcribed independently from AVM, written out
 *      in full below. Absolute numbers, not round-trips.
 *   2. 1-D kernel tests. Rounding (including the negative-value behaviour of
 *      svt_av2_tx_round_shift), the shift, and the clamp range are pinned.
 *   3. Inverse-block tests against an independent model. The model is a direct
 *      matrix multiply using the AVM reading order (the matrix COLUMN indexed by
 *      the output sample), transcribed in this file independently of the module.
 *      This is the decoder-specified direction and is compared bit-exactly.
 *   4. Forward-block tests. The forward transform is NOT a specified process
 *      (docs/m1-m2-contracts.md section 3), so it is pinned only against its own
 *      independent matrix model and against the documented degenerate cases
 *      (constant block -> pure DC). A forward+inverse round trip is never used as
 *      the correctness criterion.
 *   5. Boundary / degenerate inputs required by the task file: all-zero,
 *      constant/DC, single impulse, horizontal and vertical stripes, largest
 *      positive and negative residual, alternating extremes, a single AC
 *      coefficient, and a negative coefficient. Plus fixed-seed random blocks
 *      (>= 100 per size) for every supported geometry.
 *
 * The module's coefficient layout under test is raster, `coeff[y * width + x]`,
 * index 0 = DC, per transform.h.
 */
