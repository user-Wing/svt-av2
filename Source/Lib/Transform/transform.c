/* --- shared rounding ------------------------------------------------------- */

int32_t svt_av2_tx_round_shift(int64_t value, int bit) {
    /*
     * avm/av2/common/av2_txfm.h: round_shift():
     *   return (int32_t)((value + (1ll << (bit - 1))) >> bit);
     * The right shift is arithmetic on the signed value, so the effective
     * rounding is "add half, then floor". For negative values this is NOT
     * round-half-away-from-zero. The tests pin both signs.
     */
    return (int32_t)((value + ((int64_t)1 << (bit - 1))) >> bit);
}

/* --- 1-D kernels ----------------------------------------------------------- */

/*
 * Forward 1-D DCT-II, matching avm/av2/encoder/hybrid_fwd_txfm.c's
 * fwd_txfm_dct2_sizeN_c().
 *
 * The AVM butterfly pre-adds the symmetric pairs and then applies two columns
 * of the kernel matrix. That is exactly the full matrix product
 *   dst[freq] = sum_sample matrix[freq * size + sample] * src[sample]
 * evaluated in a different order; the tests assert equality against the direct
 * matrix form so the algebraic identity is verified rather than assumed.
 *
 * `add = (shift > 0) ? (1 << (shift - 1)) : 0` mirrors AVM, and the shift is an
 * arithmetic right shift. There is NO clamp in the forward direction.
 */
void svt_av2_tx_fwd_1d(const int* src, int* dst, int shift, uint32_t size, uint32_t count) {
    const int* matrix = dct2_matrix_for(size);
    const int add = (shift > 0) ? (1 << (shift - 1)) : 0;
    if (size == 4u) {
        for (uint32_t i = 0; i < count; ++i) {
            const int64_t a = (int64_t)src[0] + src[3], b = (int64_t)src[1] + src[2];
            const int64_t c = (int64_t)src[0] - src[3], d = (int64_t)src[1] - src[2];
            dst[0] = (int)((64 * (a + b) + add) >> shift);
            dst[1] = (int)((83 * c + 35 * d + add) >> shift);
            dst[2] = (int)((64 * (a - b) + add) >> shift);
            dst[3] = (int)((35 * c - 83 * d + add) >> shift);
            src += 4; dst += 4;
        }
        return;
    }
    for (uint32_t i = 0; i < count; ++i) {
        int64_t even[SVT_AV2_TX_MAX_DIM], odd[SVT_AV2_TX_MAX_DIM / 2];
        for (uint32_t k = 0; k < size; ++k) even[k] = src[i * size + k];
        /* Each even branch has the same mirrored symmetry at half length.
         * No rounding occurs until a complete frequency sum is available. */
        for (uint32_t span = size, step = 1u; span > 1u; span >>= 1u, step <<= 1u) {
            const uint32_t half = span >> 1u;
            for (uint32_t k = 0; k < half; ++k) {
                const int64_t a = even[k], b = even[span - 1u - k];
                odd[k] = a - b;
                even[k] = a + b;
            }
            for (uint32_t freq = step; freq < size; freq += 2u * step) {
                int64_t sum = 0;
                for (uint32_t k = 0; k < half; ++k)
                    sum += matrix[freq * size + k] * odd[k];
                dst[i * size + freq] = (int)((sum + add) >> shift);
            }
        }
        dst[i * size] = (int)((matrix[0] * even[0] + add) >> shift);
    }
}

/* Build mirrored output pairs from even and odd frequencies. The partial
 * sums remain int64, matching the range of the original full matrix product. */
void svt_av2_tx_inv_1d(const int* src,
                       int* dst,
                       int shift,
                       uint32_t size,
                       uint32_t count,
                       int coef_min,
                       int coef_max) {
    const int* matrix = dct2_matrix_for(size);
    const int add = 1 << (shift - 1);
    if (size == 4u) {
        for (uint32_t i = 0; i < count; ++i) {
            const int64_t a = 64 * ((int64_t)src[0] + src[2]);
            const int64_t b = 64 * ((int64_t)src[0] - src[2]);
            const int64_t c = 83 * (int64_t)src[1] + 35 * (int64_t)src[3];
            const int64_t d = 35 * (int64_t)src[1] - 83 * (int64_t)src[3];
            const int64_t sums[4] = {a + c, b + d, b - d, a - c};
            for (uint32_t k = 0; k < 4u; ++k) {
                int value = (int)((sums[k] + add) >> shift);
                if (value < coef_min) value = coef_min;
                else if (value > coef_max) value = coef_max;
                dst[k] = value;
            }
            src += 4; dst += 4;
        }
        return;
    }
    for (uint32_t i = 0; i < count; ++i) {
        uint32_t end = size;
        while (end > 1u && src[i * size + end - 1u] == 0) --end;
        if (end == 1u) {
            int value = (int)(((int64_t)matrix[0] * src[i * size] + add) >> shift);
            if (value < coef_min) value = coef_min;
            else if (value > coef_max) value = coef_max;
            for (uint32_t k = 0u; k < size; ++k) dst[i * size + k] = value;
            continue;
        }
        int64_t even[SVT_AV2_TX_MAX_DIM], next[SVT_AV2_TX_MAX_DIM];
        even[0] = (int64_t)matrix[0] * src[i * size];
        for (uint32_t step = size >> 1u, half = 1u; step != 0u; step >>= 1u, half <<= 1u) {
            for (uint32_t k = 0; k < half; ++k) {
                int64_t odd = 0;
                for (uint32_t freq = step; freq < end; freq += 2u * step)
                    odd += (int64_t)matrix[freq * size + k] * src[i * size + freq];
                next[k] = even[k] + odd;
                next[2u * half - 1u - k] = even[k] - odd;
            }
            for (uint32_t k = 0; k < 2u * half; ++k) even[k] = next[k];
        }
        for (uint32_t k = 0; k < size; ++k) {
            int value = (int)((even[k] + add) >> shift);
            if (value < coef_min) value = coef_min;
            else if (value > coef_max) value = coef_max;
            dst[i * size + k] = value;
        }
    }
}

