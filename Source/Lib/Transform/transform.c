/* log2 of a power-of-two dimension, as AVM's tx_size_wide_log2/high_log2 give.
 * Only ever called on a geometry that already passed svt_av2_tx_supported(),
 * so v is one of {4,8,16,32,64}. The explicit bound keeps the loop finite even
 * if that invariant is ever broken (1u << l is UB for l >= 32, which would
 * otherwise spin forever); it does not change any reachable result. */
static int tx_log2(uint32_t v) {
    int l = 0;
    while ((1u << l) < v && l < 31) {
        ++l;
    }
    return l;
}

