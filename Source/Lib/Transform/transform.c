/* Four independent sums reuse the source vector without assuming that the
 * frozen tuned ADST matrix is symmetric. */
static void adst_fwd_1d(const int* src, int* dst, int shift, uint32_t size, uint32_t flipped) {
    const int* matrix = adst_matrix_for(size);
#if M6_FLIP_TX
    if (flipped) matrix=size==4u?k_fdst_size4:size==8u?k_fdst_size8:k_fdst_size16;
#else
    (void)flipped;
#endif
    for (uint32_t out = 0u; out < size; out += 4u) {
        const int* row = matrix + out * size;
        int64_t a = 0, b = 0, c = 0, d = 0;
        for (uint32_t k = 0u; k < size; ++k) {
            const int64_t value = src[k];
            a += row[k] * value;
            b += row[size + k] * value;
            c += row[2u * size + k] * value;
            d += row[3u * size + k] * value;
        }
        dst[out] = svt_av2_tx_round_shift(a, shift);
        dst[out + 1u] = svt_av2_tx_round_shift(b, shift);
        dst[out + 2u] = svt_av2_tx_round_shift(c, shift);
        dst[out + 3u] = svt_av2_tx_round_shift(d, shift);
    }
}

static void adst_inv_1d(const int* src, int* dst, int shift, uint32_t size, int lo, int hi, uint32_t flipped) {
    const int* matrix = adst_matrix_for(size);
#if M6_FLIP_TX
    if (flipped) matrix=size==4u?k_fdst_size4:size==8u?k_fdst_size8:k_fdst_size16;
#else
    (void)flipped;
#endif
    for (uint32_t out = 0u; out < size; out += 4u) {
        int64_t a = 0, b = 0, c = 0, d = 0;
        for (uint32_t k = 0u; k < size; ++k) {
            const int* row = matrix + k * size + out;
            const int64_t value = src[k];
            a += row[0] * value; b += row[1] * value;
            c += row[2] * value; d += row[3] * value;
        }
        const int64_t sums[4] = {a, b, c, d};
        for (uint32_t k = 0u; k < 4u; ++k) {
            const int value = svt_av2_tx_round_shift(sums[k], shift);
            dst[out + k] = value < lo ? lo : value > hi ? hi : value;
        }
    }
}

/* These primary transforms retain TX_CLASS_2D and the existing raster scan. */
SvtAv2TransformStatus svt_av2_fwd_transform_type_bd(const int16_t* residual,
    int32_t* coeff, uint32_t width, uint32_t height, uint32_t bit_depth, uint32_t tx_type) {
    if (tx_type == 0u) return svt_av2_fwd_transform_bd(residual, coeff, width, height, bit_depth);
    if (residual == NULL || coeff == NULL) return SVT_AV2_TX_ERR_NULL;
    const int small_rect = (width == 8u && height == 16u) || (width == 16u && height == 8u);
    if (tx_type < 1u || tx_type > (M6_FLIP_TX ? 8u : 3u) || (width != height && !small_rect) ||
        adst_matrix_for(width) == NULL || adst_matrix_for(height) == NULL ||
        (bit_depth != 8u && bit_depth != 10u)) return SVT_AV2_TX_ERR_UNSUPPORTED;
    static const uint8_t vertical_type[9]={0,1,0,1,2,0,2,1,2};
    static const uint8_t horizontal_type[9]={0,0,1,1,0,2,2,2,1};
    const uint32_t vertical=vertical_type[tx_type],horizontal=horizontal_type[tx_type];
    const int maximum = (int)((1u << bit_depth) - 1u);
    int tmp[256], vector[16];
    int first, second;
    svt_av2_tx_fwd_shifts(width, height, &first, &second);
    for (uint32_t y = 0u; y < height; ++y)
        for (uint32_t x = 0u; x < width; ++x)
            if (residual[y * width + x] < -maximum || residual[y * width + x] > maximum)
                return SVT_AV2_TX_ERR_RANGE;
    for (uint32_t x = 0u; x < width; ++x) {
        for (uint32_t y = 0u; y < height; ++y) vector[y] = residual[y * width + x];
        if (vertical == 0u) svt_av2_tx_fwd_1d(vector, tmp + x * height, first, height, 1u);
        else adst_fwd_1d(vector, tmp + x * height, first, height, vertical==2u);
    }
    for (uint32_t fy = 0u; fy < height; ++fy) {
        for (uint32_t x = 0u; x < width; ++x) vector[x] = tmp[x * height + fy];
        if (horizontal == 0u) svt_av2_tx_fwd_1d(vector, coeff + fy * width, second, width, 1u);
        else adst_fwd_1d(vector, coeff + fy * width, second, width, horizontal==2u);
    }
    if (small_rect)
        for (uint32_t i = 0u; i < width * height; ++i)
            coeff[i] = svt_av2_tx_round_shift((int64_t)coeff[i] * SVT_AV2_TX_NEW_SQRT2,
                SVT_AV2_TX_SQRT2_BITS);
    return SVT_AV2_TX_OK;
}

SvtAv2TransformStatus svt_av2_inv_transform_type_bd(const int32_t* dqcoeff,
    int16_t* residual, uint32_t width, uint32_t height, uint32_t bit_depth, uint32_t tx_type) {
    if (tx_type == 0u) return svt_av2_inv_transform_bd(dqcoeff, residual, width, height, bit_depth);
    if (dqcoeff == NULL || residual == NULL) return SVT_AV2_TX_ERR_NULL;
    const int small_rect = (width == 8u && height == 16u) || (width == 16u && height == 8u);
    if (tx_type < 1u || tx_type > (M6_FLIP_TX ? 8u : 3u) || (width != height && !small_rect) ||
        adst_matrix_for(width) == NULL || adst_matrix_for(height) == NULL ||
        (bit_depth != 8u && bit_depth != 10u)) return SVT_AV2_TX_ERR_UNSUPPORTED;
    static const uint8_t vertical_type[9]={0,1,0,1,2,0,2,1,2};
    static const uint8_t horizontal_type[9]={0,0,1,1,0,2,2,2,1};
    const uint32_t vertical=vertical_type[tx_type],horizontal=horizontal_type[tx_type];
    const int lo = -(1 << (bit_depth + 7u)), hi = (1 << (bit_depth + 7u)) - 1;
    int block[256], tmp[256], vector[16];
    int first, second;
    svt_av2_tx_inv_shifts(width, height, &first, &second);
    for (uint32_t i = 0u; i < width * height; ++i) {
        const int v = small_rect ? svt_av2_tx_round_shift((int64_t)dqcoeff[i] * SVT_AV2_TX_NEW_INV_SQRT2,
            SVT_AV2_TX_SQRT2_BITS) : dqcoeff[i];
        block[i] = v < lo ? lo : v > hi ? hi : v;
    }
    for (uint32_t y = 0u; y < height; ++y) {
        if (horizontal == 0u) svt_av2_tx_inv_1d(block + y * width, vector, first, width, 1u, lo, hi);
        else adst_inv_1d(block + y * width, vector, first, width, lo, hi, horizontal==2u);
        for (uint32_t x = 0u; x < width; ++x) tmp[x * height + y] = vector[x];
    }
    const int out_lo = -(1 << bit_depth), out_hi = (1 << bit_depth) - 1;
    for (uint32_t x = 0u; x < width; ++x) {
        if (vertical == 0u) svt_av2_tx_inv_1d(tmp + x * height, vector, second, height, 1u, out_lo, out_hi);
        else adst_inv_1d(tmp + x * height, vector, second, height, out_lo, out_hi, vertical==2u);
        for (uint32_t y = 0u; y < height; ++y) residual[y * width + x] = (int16_t)vector[y];
    }
    return SVT_AV2_TX_OK;
}

/* --- block transforms ------------------------------------------------------ */

/*
 * AVM's two-pass structure, reproduced exactly.
 *
 * Both kernels share one shape:
 *   - READ:  `size` samples starting at the vector pointer, `pointer += size`
 *            per output line (i.e. CONTIGUOUS reads of one row)
 *   - WRITE: `dst[k * line + j]` for k in [0,size), `dst++` per output line
 *            (i.e. STRIDED writes, transposing)
 *
 * Inverse, avm/av2/common/idct.c:724-728:
 *   pass 1: inv_transform_1d(block -> tmp, shift_1st, line = height, size = width)
 *   pass 2: inv_transform_1d(tmp  -> block, shift_2nd, line = width,  size = height)
 * Expanded for a row-major `w x h` block:
 *   pass 1: for j in [0,h):  tmp[k*h + j] = T_w(block[j*w .. j*w+w-1])[k]
 *           -> tmp is row-major with `h` columns: tmp[k*h + j]
 *   pass 2: for k in [0,w):  block[f*w + k] = T_h(tmp[k*h .. k*h+h-1])[f]
 *           -> `block` is row-major `h x w` again, i.e. raster.
 *
 * Forward, avm/av2/encoder/hybrid_fwd_txfm.c:998-1001:
 *   pass 1: fwd_transform_1d(coeff -> buf,   shift_1st, line = width,  size = height)
 *   pass 2: fwd_transform_1d(buf   -> coeff, shift_2nd, line = height, size = width)
 * The forward kernel reads `src[k*line]` (STRIDED) and writes contiguously -
 * the mirror image of the inverse kernel. So both directions are "transposing"
 * passes, but the transpose sits on opposite sides.
 *
 * Do not "simplify" this into a naive row-then-column loop: that changes the
 * order in which the two shifts and the two clamp ranges are applied and is not
 * bit-exact. Verified against a literal transcription of both AVM drivers; see
 * the T009 report for the harness.
 */

static SvtAv2TransformStatus inv_transform_internal(const int32_t* dqcoeff,
                                                    int16_t* residual,
                                                    uint32_t width,
                                                    uint32_t height, uint32_t bit_depth) {
    /*
     * AVM's inv_txfm_c() clamps the working kernel size to MAX_TX_SIZE/2 = 32 on
     * each axis (idct.c:648-649). For TX_64X64 that means a 32x32 kernel whose
     * output is then upsampled 2x2 (idct.c:730-751). skipWidth/skipHeight are
     * therefore always 0 here; the coefficient reader only consumes
     * AVMMIN(1024, w*h) entries (idct.c:705,708), which for 64x64 is 1024.
     */
    const uint32_t kw = (width > 32) ? 32 : width;
    const uint32_t kh = (height > 32) ? 32 : height;
    const size_t kcount = (size_t)kw * (size_t)kh;

    int block[SVT_AV2_TX_MAX_PELS];
    int tmp[SVT_AV2_TX_MAX_PELS];
    int out[SVT_AV2_TX_MAX_PELS];

    /*
     * Step 1 - sqrt2 normalisation, avm/av2/common/idct.c:700-706.
     * Applies only when log2(width) + log2(height) is odd, i.e. exactly the
     * sizes whose aspect ratio is 2:1: 4x8/8x4 (2^2 * 2^3), 4x16/16x4
     * (2^2 * 2^4) and 8x16/16x8 (2^3 * 2^4). Note the log2 uses the REAL tx_size
     * dimensions (log2w = 6 for 64), not the clamped kernel size.
     */
    const int log2w = tx_log2(width);
    const int log2h = tx_log2(height);
    const int sqrt2 = ((log2w + log2h) & 1) ? 1 : 0;

    const int intermediate_bd = (int)bit_depth + 8; /* bd + 8 */
    const int rng_min = -(1 << (intermediate_bd - 1));
    const int rng_max = (1 << (intermediate_bd - 1)) - 1;
    const int col_rng_min = -(1 << bit_depth); /* -(1 << bd) */
    const int col_rng_max = (1 << bit_depth) - 1;

    for (size_t i = 0; i < kcount; ++i) {
        int v = sqrt2 ? svt_av2_tx_round_shift((int64_t)dqcoeff[i] * SVT_AV2_TX_NEW_INV_SQRT2,
                                               SVT_AV2_TX_SQRT2_BITS)
                      : (int)dqcoeff[i];
        /* idct.c:710 clamp_buf(block, n, bd + 8). */
        if (v < rng_min) {
            v = rng_min;
        } else if (v > rng_max) {
            v = rng_max;
        }
        block[i] = v;
    }

    int shift_1st = 0;
    int shift_2nd = 0;
    svt_av2_tx_inv_shifts(width, height, &shift_1st, &shift_2nd);

    /* Test the normalized and input-clipped grid. Both original 1-D passes
     * retain their rounding and clipping; the 64-side replication is constant. */
    int only_dc = 1;
    for (size_t i = 1u; i < kcount; ++i) {
        if (block[i] != 0) { only_dc = 0; break; }
    }
    if (only_dc) {
        svt_av2_tx_inv_1d(block, out, shift_1st, kw, 1u, rng_min, rng_max);
        for (uint32_t i = 0u; i < kh; ++i) tmp[i] = 0;
        tmp[0] = out[0];
        svt_av2_tx_inv_1d(tmp, out, shift_2nd, kh, 1u, col_rng_min, col_rng_max);
        for (size_t i = 0u; i < (size_t)width * height; ++i) residual[i] = (int16_t)out[0];
        return SVT_AV2_TX_OK;
    }

    /*
     * Pass 1: for each of the `kh` rows of the row-major kernel block,
     * transform the `kw` samples along x, writing the result transposed into
     * `tmp` (tmp[k*kh + j]). Clamped to the intermediate (bd+8) range.
     */
    for (uint32_t j = 0; j < kh; ++j) {
        svt_av2_tx_inv_1d(block + j * kw, out, shift_1st, kw, 1, rng_min, rng_max);
        for (uint32_t k = 0; k < kw; ++k) {
            tmp[k * kh + j] = out[k];
        }
    }

    /*
     * Pass 2: for each of the `kw` rows of `tmp` (each of length `kh`),
     * transform along y, writing the result transposed into `block`
     * (block[f*kw + k]). Clamped to the pixel range.
     *
     * The clamp is [-256, 255], NOT [0, 255]: this stage produces a RESIDUAL.
     * Adding the prediction and clipping to [0,255] belongs to T012.
     */
    for (uint32_t k = 0; k < kw; ++k) {
        svt_av2_tx_inv_1d(tmp + k * kh, out, shift_2nd, kh, 1, col_rng_min, col_rng_max);
        for (uint32_t f = 0; f < kh; ++f) {
            block[f * kw + k] = out[f];
        }
    }

    /*
     * Upsample, idct.c:730-751. When the working width is 32 but the real
     * tx_size width is 64, each sample is copied into two horizontally adjacent
     * positions; likewise vertically. For every other size (kw == width and
     * kh == height) this is a straight copy.
     */
    const uint32_t uw = (width > 32) ? 2 : 1;
    const uint32_t uh = (height > 32) ? 2 : 1;
    for (uint32_t y = 0; y < kh; ++y) {
        for (uint32_t x = 0; x < kw; ++x) {
            const int16_t v = (int16_t)block[y * kw + x];
            for (uint32_t dy = 0; dy < uh; ++dy) {
                for (uint32_t dx = 0; dx < uw; ++dx) {
                    residual[(y * uh + dy) * width + (x * uw + dx)] = v;
                }
            }
        }
    }
    return SVT_AV2_TX_OK;
}

SvtAv2TransformStatus svt_av2_inv_transform(const int32_t* dqcoeff,
                                            int16_t* residual,
                                            uint32_t width,
                                            uint32_t height) {
    return svt_av2_inv_transform_bd(dqcoeff, residual, width, height, 8);
}

SvtAv2TransformStatus svt_av2_inv_transform_bd(const int32_t* dqcoeff,
                                            int16_t* residual,
                                            uint32_t width,
                                            uint32_t height, uint32_t bit_depth) {
    if (dqcoeff == NULL || residual == NULL) {
        return SVT_AV2_TX_ERR_NULL;
    }
    if (!svt_av2_tx_supported(width, height)) {
        return SVT_AV2_TX_ERR_UNSUPPORTED;
    }
    if (bit_depth != 8 && bit_depth != 10) return SVT_AV2_TX_ERR_UNSUPPORTED;
    return inv_transform_internal(dqcoeff, residual, width, height, bit_depth);
}

SvtAv2TransformStatus svt_av2_fwd_transform(const int16_t* residual,
                                            int32_t* coeff,
                                            uint32_t width,
                                            uint32_t height) {
    return svt_av2_fwd_transform_bd(residual, coeff, width, height, 8);
}

SvtAv2TransformStatus svt_av2_fwd_transform_bd(const int16_t* residual,
                                            int32_t* coeff,
                                            uint32_t width,
                                            uint32_t height, uint32_t bit_depth) {
    if (residual == NULL || coeff == NULL) {
        return SVT_AV2_TX_ERR_NULL;
    }
    if (!svt_av2_tx_supported(width, height)) {
        return SVT_AV2_TX_ERR_UNSUPPORTED;
    }

    if (bit_depth != 8 && bit_depth != 10) return SVT_AV2_TX_ERR_UNSUPPORTED;
    const int32_t maximum = (int32_t)((1u << bit_depth) - 1u);
    const size_t count = (size_t)width * (size_t)height;
    unsigned variation = 0u;
    for (size_t i = 0; i < count; ++i) {
        if (residual[i] < -maximum || residual[i] > maximum) {
            return SVT_AV2_TX_ERR_RANGE;
        }
        variation |= (unsigned)(residual[i] ^ residual[0]);
    }
    if (!variation) {
        int vector[64], vertical[64], horizontal[64];
        int first, second;
        svt_av2_tx_fwd_shifts(width, height, &first, &second);
        for (uint32_t y = 0u; y < height; ++y) vector[y] = residual[0];
        /* Every column has identical input. Reuse its exact first pass. */
        svt_av2_tx_fwd_1d(vector, vertical, first, height, 1u);
        const uint32_t cw = width > 32u ? 32u : width;
        const uint32_t ch = height > 32u ? 32u : height;
        for (uint32_t fy = 0u; fy < ch; ++fy) {
            if (vertical[fy]) {
                for (uint32_t x = 0u; x < width; ++x) vector[x] = vertical[fy];
                svt_av2_tx_fwd_1d(vector, horizontal, second, width, 1u);
                for (uint32_t x = 0u; x < cw; ++x) coeff[fy * cw + x] = horizontal[x];
            } else {
                for (uint32_t x = 0u; x < cw; ++x) coeff[fy * cw + x] = 0;
            }
        }
        if ((tx_log2(width) + tx_log2(height)) & 1)
            for (uint32_t i = 0u; i < cw * ch; ++i)
                coeff[i] = svt_av2_tx_round_shift((int64_t)coeff[i] * SVT_AV2_TX_NEW_SQRT2,
                    SVT_AV2_TX_SQRT2_BITS);
        return SVT_AV2_TX_OK;
    }

    int buf[SVT_AV2_TX_MAX_PELS];
    int out[SVT_AV2_TX_MAX_PELS];
    int coeff_buf[SVT_AV2_TX_MAX_PELS];

    for (size_t i = 0; i < count; ++i) {
        coeff_buf[i] = residual[i];
    }

    int shift_1st = 0;
    int shift_2nd = 0;
    svt_av2_tx_fwd_shifts(width, height, &shift_1st, &shift_2nd);

    /*
     * Pass 1: fwd_transform_1d(coeff -> buf, shift_1st, line = width, size = height).
     * The forward kernel reads `src[k*line]`, so with `line = width` and the
     * input being the row-major residual block, vector `j` is the COLUMN x = j
     * (src[k*width + j] = element (x = j, y = k)). It transforms along y and
     * writes contiguously, so `buf` ends up row-major with `height` columns.
     */
    for (uint32_t j = 0; j < width; ++j) {
        for (uint32_t k = 0; k < height; ++k) {
            out[k] = coeff_buf[k * width + j];
        }
        svt_av2_tx_fwd_1d(out, buf + j * height, shift_1st, height, 1);
    }

    /*
     * Pass 2: fwd_transform_1d(buf -> coeff, shift_2nd, line = height, size = width).
     * `buf` is row-major with `height` columns, indexed `buf[x * height + fy]`.
     * With `line = height` the kernel reads `src[k*height]` for k in [0,width),
     * i.e. the COLUMN x = 0..width-1 at fixed fy: the transform runs along x for
     * each y-frequency. It writes contiguously with `dst += width` per fy, so
     * `coeff[fy * width + fx]` - raster, which is the caller-facing layout.
     */
    const uint32_t fwd2_lines = (height > 32) ? 32 : height;
    for (uint32_t fy = 0; fy < fwd2_lines; ++fy) {
        for (uint32_t x = 0; x < width; ++x) {
            out[x] = buf[x * height + fy];
        }
        /* NOT in-place: svt_av2_tx_fwd_1d reads src as it writes dst. */
        svt_av2_tx_fwd_1d(out, coeff_buf + fy * width, shift_2nd, width, 1);
    }

    /*
     * Emit. For the sizes this round originally froze (all dimensions <= 16) the
     * kernel buffer is already the caller-facing raster layout and the length is
     * w*h. For TX_64X64 the AVM driver zeroes the high half (both the pass-2
     * skip_line memset over the last 32 lines and the per-line zero_line memset
     * over frequencies 32..63, hybrid_fwd_txfm.c:350-359) and then re-packs the
     * surviving 32x32 low-frequency grid into the first 1024 indices
     * (hybrid_fwd_txfm.c:1003-1008). av2_get_max_eob() carries 1024 for
     * TX_64X64, so the caller-facing array is 1024 long and matches the decoder
     * read (idct.c:705,708).
     */
    const size_t out_count = svt_av2_tx_coeff_count(width, height);
    if (width > 32) {
        /* Re-pack rows 1..h-1 of the 32x32 low-frequency grid to stride 32. */
        for (uint32_t row = 1; row < fwd2_lines; ++row) {
            for (uint32_t x = 0; x < 32; ++x) {
                coeff[row * 32 + x] = coeff_buf[row * width + x];
            }
        }
        for (uint32_t x = 0; x < 32; ++x) {
            coeff[x] = coeff_buf[x];
        }
    } else {
        for (size_t i = 0; i < out_count; ++i) {
            coeff[i] = coeff_buf[i];
        }
    }
    /* AVM applies odd-log2 sqrt2 normalization after packing, so every
     * carried coefficient of a 64-wide rectangle receives the same factor. */
    if ((tx_log2(width) + tx_log2(height)) & 1) {
        for (size_t i = 0; i < out_count; ++i)
            coeff[i] = svt_av2_tx_round_shift((int64_t)coeff[i] * SVT_AV2_TX_NEW_SQRT2,
                SVT_AV2_TX_SQRT2_BITS);
    }
    return SVT_AV2_TX_OK;
}
